"use client"

import { UploadIcon } from "lucide-react"
import { useShell } from "@/components/app-shell"
import { Composer } from "@/components/chat/composer"
import { Logo } from "@/components/logo"
import { Button } from "@/components/ui/button"
import { displayTitle } from "@/lib/api"
import { categoryMeta } from "@/lib/categories"
import { useLibrary } from "@/lib/store"

export function Welcome({ onAsk, busy }: { onAsk: (q: string) => void; busy: boolean }) {
  const { documents, loaded } = useLibrary()
  const { openIngest } = useShell()
  const ready = documents.filter((d) => d.status === "ready")
  const pages = ready.reduce((n, d) => n + d.pageCount, 0)
  const ocrPages = ready.reduce((n, d) => n + d.ocrPageCount, 0)

  // Questions were generated by the local LLM at ingestion: one per document,
  // skipping vague ones, newest documents first.
  const suggestions = ready
    .flatMap((d) =>
      d.questions
        .filter(isGoodSuggestion)
        .slice(0, 1)
        .map((q) => ({ q, from: displayTitle(d), color: categoryMeta(d.category).color }))
    )
    .slice(0, 4)

  return (
    <div className="relative isolate flex min-h-full flex-col items-center overflow-hidden px-6 pt-16 pb-12">
      <Chakra />
      <div className="flex w-full max-w-[820px] flex-col items-center gap-8">
        <div className="flex flex-col items-center gap-3.5 text-center">
          <Logo size={76} />
          <div className="flex items-center gap-2.5 text-xs font-semibold tracking-[0.1em] text-gold-ink uppercase">
            <span className="h-px w-6 bg-gold" />
            <span lang="hi" className="tracking-normal">सत्यमेव जयते</span> · Knowledge desk
            <span className="h-px w-6 bg-gold" />
          </div>
          <h2 className="max-w-[760px] font-serif text-[clamp(34px,5vw,56px)] leading-[1.04] font-medium tracking-[-0.025em] text-balance">
            Every order, circular and notification.{" "}
            <em className="text-primary">One question away.</em>
          </h2>
          <p className="max-w-[560px] text-[17px] leading-relaxed text-ink-2">
            Ask in English, Hindi or Hinglish. Every answer cites the page it came from, scanned gazettes included.
          </p>
        </div>

        <div className="w-full">
          <Composer onSend={onAsk} busy={busy} large placeholder="e.g. Who will exercise the powers under UAPA in Delhi?" />
        </div>

        {loaded && ready.length > 0 && (
          <dl className="grid w-full grid-cols-2 border-y border-[#EEF1F6] sm:grid-cols-4">
            <Stat value={ready.length} label="documents" />
            <Stat value={pages} label="pages indexed" />
            <Stat value={ocrPages} label="scanned pages read by OCR" />
            <Stat value={0} label="bytes sent to the cloud" />
          </dl>
        )}

        {suggestions.length > 0 ? (
          <section className="flex w-full flex-col gap-3">
            <h3 className="eyebrow">Start with a question</h3>
            <div className="grid gap-3 sm:grid-cols-2">
              {suggestions.map((s) => (
                <button
                  key={s.q}
                  onClick={() => onAsk(s.q)}
                  disabled={busy}
                  className="flex flex-col gap-2.5 rounded-[18px] border bg-card px-[18px] py-4 text-left shadow-[0_1px_2px_rgba(13,23,51,0.04)] transition-all hover:-translate-y-px hover:border-primary/30 hover:shadow-[0_10px_24px_rgba(13,23,51,0.07)]"
                >
                  <span className="text-[15px] leading-snug">{s.q}</span>
                  <span className="flex items-center gap-2 text-xs text-muted-foreground">
                    <span className="size-2 shrink-0 rounded-[3px]" style={{ background: s.color }} />
                    <span className="truncate">{s.from}</span>
                  </span>
                </button>
              ))}
            </div>
          </section>
        ) : (
          loaded &&
          ready.length === 0 && (
            <div className="flex flex-col items-center gap-3 rounded-[22px] border border-dashed border-[#B9C6E4] bg-[#F7F9FF] p-8 text-center">
              <p className="text-sm text-muted-foreground">
                The library is empty. Add PDFs, Word files or text to start asking questions.
              </p>
              <Button onClick={openIngest}>
                <UploadIcon />
                Ingest documents
              </Button>
            </div>
          )
        )}
      </div>
    </div>
  )
}

function Stat({ value, label }: { value: number; label: string }) {
  return (
    <div className="flex flex-col-reverse items-center gap-1.5 px-2 py-4 text-center sm:not-first:border-l sm:border-[#EEF1F6]">
      <dt className="text-xs text-muted-foreground">{label}</dt>
      <dd className="font-serif text-[30px] leading-none font-medium tabular-nums">{value}</dd>
    </div>
  )
}

/** Faint chakra-style seal behind the headline (decorative). */
function Chakra() {
  return (
    <svg
      aria-hidden
      viewBox="-100 -100 200 200"
      className="pointer-events-none absolute top-[-330px] left-1/2 -z-10 size-[760px] -translate-x-1/2 opacity-60"
    >
      <circle r="96" fill="none" stroke="#E7ECF8" strokeWidth=".6" />
      <circle r="78" fill="none" stroke="#E7ECF8" strokeWidth=".6" />
      <circle r="22" fill="none" stroke="#F5E3B8" strokeWidth=".8" />
      <g stroke="#EDF1FA" strokeWidth=".5">
        {Array.from({ length: 12 }, (_, i) => (
          <line key={i} x1="-78" y1="0" x2="78" y2="0" transform={`rotate(${i * 15})`} />
        ))}
      </g>
    </svg>
  )
}

const VAGUE =
  /subject of|scope of|serial number|rank of|who is the (lieutenant|lt\.?)|authority responsible|authorized to (make|publish)|who is appointed|responsible for addressing/i

function isGoodSuggestion(q: string) {
  return q.length >= 25 && q.length <= 95 && !VAGUE.test(q)
}
