"use client"

import { ArrowRightIcon, UploadIcon } from "lucide-react"
import { useShell } from "@/components/app-shell"
import { Composer } from "@/components/chat/composer"
import { Button } from "@/components/ui/button"
import { displayTitle } from "@/lib/api"
import { useLibrary } from "@/lib/store"

export function Welcome({ onAsk, busy }: { onAsk: (q: string) => void; busy: boolean }) {
  const { documents, health, loaded } = useLibrary()
  const { openIngest, openLibrary } = useShell()
  const ready = documents.filter((d) => d.status === "ready")
  const pages = ready.reduce((n, d) => n + d.pageCount, 0)

  // Questions were generated by the local LLM at ingestion. Keep short,
  // concrete ones (one per document) and skip the vague patterns it produces.
  const suggestions = ready
    .flatMap((d) =>
      d.questions.filter(isGoodSuggestion).slice(0, 1).map((q) => ({ q, from: displayTitle(d) }))
    )
    .slice(0, 4)

  return (
    <div className="mx-auto flex min-h-full w-full max-w-3xl flex-col justify-center gap-7 px-6 py-12">
      <div className="flex flex-col items-center gap-3 text-center">
        {loaded && (
          <button
            onClick={openLibrary}
            className="rounded-full bg-accent px-3 py-1 text-[13px] font-medium text-accent-foreground hover:bg-primary/10"
          >
            {ready.length} documents · {pages} pages indexed
            {health && health.stats.pending > 0 && ` · ${health.stats.pending} ingesting`}
          </button>
        )}
        <h2 className="text-[34px] leading-[1.2] font-bold tracking-tight">
          Ask your documents.
          <br />
          <span className="text-slate-500">Get the answer, and the page it came from.</span>
        </h2>
        <p className="max-w-xl text-base text-slate-600">
          Notifications, circulars and guidelines, including scanned ones. Ask in English, Hindi or
          Hinglish.
        </p>
      </div>

      <Composer onSend={onAsk} busy={busy} large />

      {suggestions.length > 0 ? (
        <div className="flex flex-col gap-2.5">
          <div className="text-[11px] font-semibold tracking-[0.06em] text-muted-foreground uppercase">
            Try one of these
          </div>
          <div className="grid gap-2.5 sm:grid-cols-2">
            {suggestions.map((s) => (
              <button
                key={s.q}
                onClick={() => onAsk(s.q)}
                disabled={busy}
                className="group rounded-xl border bg-background px-3.5 py-3 text-left text-sm transition-colors hover:border-primary/40 hover:bg-accent/40"
              >
                <span className="flex items-start gap-2">
                  <span className="flex-1">{s.q}</span>
                  <ArrowRightIcon className="mt-0.5 size-4 shrink-0 text-muted-foreground opacity-0 transition-opacity group-hover:opacity-100" />
                </span>
                <span className="mt-1 block truncate text-xs text-muted-foreground">from {s.from}</span>
              </button>
            ))}
          </div>
        </div>
      ) : (
        loaded &&
        ready.length === 0 && (
          <div className="flex flex-col items-center gap-3 rounded-2xl border border-dashed p-8 text-center">
            <p className="text-sm text-muted-foreground">
              No documents yet. Ingest PDFs, Word files or text to start asking questions.
            </p>
            <Button onClick={openIngest}>
              <UploadIcon />
              Ingest documents
            </Button>
          </div>
        )
      )}
    </div>
  )
}

const VAGUE =
  /subject of|scope of|serial number|rank of|who is the (lieutenant|lt\.?)|authority responsible|authorized to (make|publish)|who is appointed|responsible for addressing/i

function isGoodSuggestion(q: string) {
  return q.length >= 25 && q.length <= 95 && !VAGUE.test(q)
}
